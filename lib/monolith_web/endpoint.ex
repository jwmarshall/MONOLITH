defmodule MonolithWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :monolith

  # Deep-link return context can contain private mail search/pagination values.
  # Encrypt as well as authenticate the browser session.
  @session_options [
    store: :cookie,
    key: "_monolith_key",
    signing_salt: "AX124byL",
    encryption_salt: "e2cY7mQp",
    same_site: "Lax",
    max_age: 43_200,
    http_only: true
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :monolith,
    gzip: not code_reloading?,
    only: MonolithWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  plug MonolithWeb.Plugs.LocalHost
  plug Plug.Session, @session_options
  plug MonolithWeb.WorkspaceReturn, :capture
  plug MonolithWeb.Plugs.OwnerSetup
  plug MonolithWeb.Plugs.GoogleSetupCredentials
  plug MonolithWeb.OwnerUnlock
  plug MonolithWeb.Plugs.GeminiCredentials
  plug MonolithWeb.Plugs.GitHubCredentials
  # Consume OAuth codes before any request instrumentation or parameter parsing.
  plug MonolithWeb.Plugs.GoogleOAuthCallback
  plug MonolithWeb.Plugs.GitHubOAuthCallback

  # This exposes code/SQL execution to development tools. Never enable remote access.
  if Mix.env() == :dev do
    plug Tidewave
  end

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :monolith
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug MonolithWeb.Plugs.OwnerRequest
end
